    /**
     * @return array<int, string> all 256 codes; unmapped codes are an empty string
     */
    public static function table(string $name): array
    {
        return self::$cache[$name] ??= self::build($name);
    }

    /** @return array<int, string> */
    private static function build(string $name): array
    {
        $t = array_fill(0, 256, '');
        if ($name === 'ZapfDingbats') {
            $t[0x20] = ' ';
            return $t;
        }
        for ($i = 0x20; $i < 0x7F; $i++) {
            $t[$i] = chr($i);
        }
        $t[0x09] = $t[0x0A] = $t[0x0D] = ' ';

        switch ($name) {
            case 'MacRomanEncoding':
                foreach (self::MAC_80 as $i => $cp) {
                    $t[0x80 + $i] = $cp === 0 ? '' : Utf::chr($cp);
                }
                break;
            case 'StandardEncoding':
                $t[0x27] = "\u{2019}";
                $t[0x60] = "\u{2018}";
                foreach (self::STD_A0 as $i => $cp) {
                    $t[$i] = Utf::chr($cp);
                }
                break;
            case 'Symbol':
                foreach (self::SYMBOL as $i => $cp) {
                    $t[$i] = Utf::chr($cp);
                }
                break;
            case 'PDFDocEncoding':
                for ($i = 0xA1; $i < 0x100; $i++) {
                    $t[$i] = Utf::chr($i);
                }
                foreach (self::PDFDOC_80 as $i => $cp) {
                    $t[$i] = Utf::chr($cp);
                }
                break;
            default: // WinAnsiEncoding, and the best guess for anything unnamed
                for ($i = 0xA0; $i < 0x100; $i++) {
                    $t[$i] = Utf::chr($i);
                }
                foreach (self::WIN_80 as $i => $cp) {
                    $t[$i] = Utf::chr($cp);
                }
                break;
        }
        return $t;
    }
